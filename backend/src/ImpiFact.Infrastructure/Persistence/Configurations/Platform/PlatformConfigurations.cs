using ImpiFact.Domain.Identity;
using ImpiFact.Domain.Platform;
using ImpiFact.Infrastructure.Persistence.Conversions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace ImpiFact.Infrastructure.Persistence.Configurations.Platform;

// Operación y plataforma (Modelo de datos detallado, sección 3.7). data_protection_keys se configura aparte,
// junto con Data Protection. La bandeja de salida y la auditoría no referencian a companies: son registros de
// operación que no deben bloquear ni depender de otra fila.

internal sealed class OutboxMessageConfiguration : IEntityTypeConfiguration<OutboxMessage>
{
    public void Configure(EntityTypeBuilder<OutboxMessage> builder)
    {
        builder.ToTable("outbox_messages");
        builder.Property(message => message.Type).HasMaxLength(100);
        builder.Property(message => message.Payload).HasJsonConversion();
        builder.Property(message => message.Status).HasStoreDefault(OutboxStatus.Pending);
        builder.Property(message => message.Attempts).HasStoreDefault(0);
        builder.Property(message => message.LockedBy).HasMaxLength(100);
        builder.Property(message => message.LastError).HasMaxLength(2000);
        builder.HasIndex(message => new { message.Status, message.NextAttemptAt });
    }
}

internal sealed class AuditLogConfiguration : IEntityTypeConfiguration<AuditLog>
{
    public void Configure(EntityTypeBuilder<AuditLog> builder)
    {
        builder.ToTable("audit_logs");

        // bigint con identidad: el proveedor de PostgreSQL la crea «generated by default as identity».
        builder.Property(log => log.Id).ValueGeneratedOnAdd();
        builder.Property(log => log.Action).HasMaxLength(100);
        builder.Property(log => log.EntityType).HasMaxLength(100);
        builder.Property(log => log.EntityId).HasMaxLength(64);
        builder.Property(log => log.CorrelationId).HasMaxLength(64);
        builder.Property(log => log.Ip).HasMaxLength(45);
        builder.Property(log => log.UserAgent).HasMaxLength(300);
        builder.Property(log => log.Changes).HasJsonConversion();
        builder.HasIndex(log => new { log.CompanyId, log.CreatedAt }).IsDescending(false, true);
        builder.HasIndex(log => new { log.EntityType, log.EntityId });
    }
}

internal sealed class NotificationConfiguration : IEntityTypeConfiguration<Notification>
{
    public void Configure(EntityTypeBuilder<Notification> builder)
    {
        builder.ToTable("notifications");
        builder.Property(notification => notification.Type).HasMaxLength(50);
        builder.Property(notification => notification.Title).HasMaxLength(200);
        builder.Property(notification => notification.Body).HasMaxLength(1000);
        builder.Property(notification => notification.IsRead).HasStoreDefault(false);
        builder.BelongsToCompany();
        builder.References<Notification, User>(notification => notification.UserId);
        builder.HasIndex(notification => new { notification.CompanyId, notification.UserId, notification.IsRead, notification.CreatedAt })
            .IsDescending(false, false, false, true);
    }
}

internal sealed class IdempotencyKeyConfiguration : IEntityTypeConfiguration<IdempotencyKey>
{
    public void Configure(EntityTypeBuilder<IdempotencyKey> builder)
    {
        builder.ToTable("idempotency_keys");
        builder.Property(key => key.Key).HasMaxLength(100);
        builder.Property(key => key.RequestHash).IsFixed(64);
        builder.Property(key => key.ResponseBody).HasJsonConversion();
        builder.BelongsToCompany();
        builder.HasIndex(key => new { key.CompanyId, key.Key }).IsUnique();
        builder.HasIndex(key => key.ExpiresAt);
    }
}
