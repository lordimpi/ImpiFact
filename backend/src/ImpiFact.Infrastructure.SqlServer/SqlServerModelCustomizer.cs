using System.Text.Json;
using ImpiFact.Infrastructure.Persistence;
using ImpiFact.Infrastructure.Persistence.Conversions;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;

namespace ImpiFact.Infrastructure.SqlServer;

/// <summary>
/// Ajustes del modelo propios de SQL Server, después de las configuraciones comunes (Modelo de datos detallado,
/// sección 8). El resto de los tipos sale del mapeo por defecto del proveedor: <c>Guid</c> a <c>uniqueidentifier</c>,
/// <c>bool</c> a <c>bit</c>, <c>string</c> a <c>nvarchar(n)</c>, <c>decimal</c> a <c>decimal(p,s)</c> con la precisión
/// explícita de cada propiedad y <c>DateTimeOffset</c> a <c>datetimeoffset</c> (7 decimales, los mismos de .NET: el
/// instante vuelve exacto y nunca queda redondeado hacia adelante).
/// </summary>
internal sealed class SqlServerModelCustomizer(ModelCustomizerDependencies dependencies) : RelationalModelCustomizer(dependencies)
{
    /// <summary>
    /// Intercalación (collation: la regla para comparar y ordenar texto) de toda columna de texto: distingue mayúsculas
    /// y acentos (<c>CS_AS</c>), como PostgreSQL. Así un índice único, un <c>=</c> o un <c>join</c> se comportan igual en
    /// los dos motores sin importar la intercalación por defecto del servidor (la de SQL Server suele no distinguir
    /// mayúsculas). <c>_SC</c> compara bien los caracteres fuera del plano básico de Unicode, como los emoji.
    /// </summary>
    internal const string TextCollation = "Latin1_General_100_CS_AS_SC";

    /// <summary>
    /// La misma intercalación sin distinguir mayúsculas pero sí acentos, como <c>ilike</c> de PostgreSQL: la usa la
    /// búsqueda de texto del dialecto (<see cref="SqlServerSqlDialect.LikeIgnoreCase"/>).
    /// </summary>
    internal const string IgnoreCaseCollation = "Latin1_General_100_CI_AS_SC";

    /// <summary>La regla de snake_case de la convención de nombres (la misma de System.Text.Json).</summary>
    private static readonly JsonNamingPolicy SnakeCase = JsonNamingPolicy.SnakeCaseLower;

    public override void Customize(ModelBuilder modelBuilder, DbContext context)
    {
        base.Customize(modelBuilder, context);

        foreach (var property in modelBuilder.Model.GetEntityTypes().Select(type => type.FindPrimaryKey())
            .Where(key => key is { Properties: [{ ValueGenerated: ValueGenerated.OnAdd } property] } && IsInteger(key.Properties[0].ClrType))
            .Select(key => key!.Properties[0]))
        {
            UseKeySequence(property);
        }

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().ToList())
        {
            foreach (var property in entityType.GetDeclaredProperties())
            {
                if (JsonColumn.IsJsonColumn(property) && property.GetColumnType() is null)
                {
                    UseJsonColumn(entityType, property);
                }
                else if (property.ClrType == typeof(string) && property.GetCollation() is null)
                {
                    property.SetCollation(TextCollation);
                }
            }
        }

        // Índices filtrados: SQL Server no tiene booleanos, así que «is_active» se compara con 1. El filtro de cufe es
        // obligatorio aquí: sin él, SQL Server trata los NULL como iguales y solo dejaría un documento sin CUFE.
        PortableIndexFilters.Apply(modelBuilder, (index, filter) => index.SetFilter(filter.Kind switch
        {
            PortableIndexFilterKind.WhereTrue => $"[{filter.Column}] = 1",
            PortableIndexFilterKind.WhereNotNull => $"[{filter.Column}] IS NOT NULL",
            _ => throw new NotSupportedException($"Index filter {filter.Kind} is not supported."),
        }));
    }

    /// <summary>
    /// Una llave numérica que genera la base (plans, audit_logs, data_protection_keys) toma su valor de una secuencia por
    /// tabla (<c>&lt;tabla&gt;_&lt;columna&gt;_seq</c>) en lugar de IDENTITY: como «generated by default as identity» de
    /// PostgreSQL, la columna toma el siguiente valor si el INSERT no trae uno y acepta el que trae. Con IDENTITY, SQL
    /// Server rechaza un id explícito (el alta y el guardado por id de los planes lo eligen en la aplicación) salvo con
    /// IDENTITY_INSERT, que es por sesión y por tabla.
    /// </summary>
    private static void UseKeySequence(IMutableProperty property)
    {
        var table = SnakeCase.ConvertName(property.DeclaringType.GetTableName()!);
        property.SetValueGenerationStrategy(SqlServerValueGenerationStrategy.Sequence);
        property.SetSequenceName($"{table}_{SnakeCase.ConvertName(property.GetColumnName())}_seq");
    }

    private static bool IsInteger(Type type) => type == typeof(int) || type == typeof(long);

    /// <summary>
    /// SQL Server 2022 no tiene tipo JSON (llega en SQL Server 2025 y Azure SQL): la columna es <c>nvarchar(max)</c> con
    /// una restricción <c>ISJSON</c> que rechaza texto que no sea JSON. <c>ISJSON(NULL)</c> es nulo y la restricción
    /// deja pasar el nulo, así una columna JSON opcional sigue siéndolo.
    /// </summary>
    /// <remarks>
    /// El personalizador corre antes de que la convención de nombres (<c>SnakeCaseNamingConvention</c>, al cerrar el
    /// modelo) pase tablas y columnas a snake_case, así que aquí se aplica la misma regla para escribir el nombre final
    /// en el SQL de la restricción. Si no coincidiera, la migración fallaría al crear la tabla.
    /// </remarks>
    private static void UseJsonColumn(IMutableEntityType entityType, IMutableProperty property)
    {
        property.SetColumnType("nvarchar(max)");
        if (entityType.GetTableName() is not { } table || entityType.BaseType is not null)
        {
            return;
        }

        var tableName = SnakeCase.ConvertName(table);
        var column = SnakeCase.ConvertName(property.GetColumnName());
        entityType.AddCheckConstraint($"ck_{tableName}_{column}_json", $"ISJSON([{column}]) = 1");
    }
}
