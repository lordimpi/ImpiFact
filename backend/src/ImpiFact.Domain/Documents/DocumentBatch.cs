using ImpiFact.Domain.Common;

namespace ImpiFact.Domain.Documents;

/// <summary>
/// A batch of documents sent together with SendBillAsync (<c>document_batches</c>; phase 7a, T8; php-rules 15). In the PHP a
/// batch was only the file <c>zip/{company}/{batch}.zip</c>, so its ZipKey was lost (php-rules 7, row 21); here the batch is
/// a row with its ZipKey and each document points to it (<see cref="Document.BatchId"/>). Its documents are issued (numbered
/// and signed) when added and wait <see cref="DocumentStatus.Queued"/> until the batch is sent.
/// </summary>
public sealed class DocumentBatch : TenantEntity
{
    /// <summary>Most documents the DIAN accepts in one ZIP of SendBillAsync (annex 1.9, sections 6.8 and 7.8.1: «Máximo 50»).</summary>
    public const int MaxDocuments = 50;

    /// <summary>Largest <c>contentFile</c> of SendBillAsync (annex 1.9, section 7.8.2: 50 MB).</summary>
    public const long MaxZipBytes = 50L * 1024 * 1024;

    /// <summary>Longest name: the PHP <c>{batch}</c> of the routes, here validated (php-rules 15.1, item 2).</summary>
    public const int MaxNameLength = 50;

    // EF Core reads and writes this field directly; the domain changes it only through the methods below.
    private DocumentBatchStatus _status = DocumentBatchStatus.Open;

    /// <summary>Name of the batch, unique in the company: the client's <c>{batch}</c> of the PHP routes, or one ImpiFact made.</summary>
    public required string Name { get; init; }

    public DocumentBatchStatus Status
    {
        get => _status;
        init => _status = value;
    }

    /// <summary>
    /// Documents added. Every addition changes the row (and its row version), so an addition and a send of the same batch
    /// at the same time cannot both be saved.
    /// </summary>
    public int DocumentCount { get; private set; }

    /// <summary>DIAN environment of the batch, the one of its first document: every document of a ZIP goes to the same service.</summary>
    public int? TypeEnvironmentId { get; private set; }

    /// <summary>Name of the ZIP sent to the DIAN (<c>z{nit}000{yy}{counter}.zip</c>, annex 1.9, section 6.8), the <c>fileName</c> of SendBillAsync.</summary>
    public string? ZipFileName { get; set; }

    /// <summary>The ZipKey (TrackId) that SendBillAsync returned, to ask GetStatusZip.</summary>
    public string? ZipKey { get; set; }

    /// <summary>The XML file of each document inside the ZIP, to match the answers that name the file and not the code.</summary>
    public List<DocumentBatchEntry>? Entries { get; set; }

    public string? DianStatusCode { get; set; }

    public string? DianStatusDescription { get; set; }

    /// <summary>Messages of the DIAN about the whole ZIP (the initial validations of SendBillAsync).</summary>
    public List<string>? ErrorMessages { get; set; }

    /// <summary>Storage key of the ZIP sent, generated by the server.</summary>
    public string? ZipFileKey { get; set; }

    /// <summary>Storage key of the SendBillAsync answer (the SOAP body), generated by the server.</summary>
    public string? ResponseFileKey { get; set; }

    public DateTimeOffset? QueuedAt { get; private set; }

    public DateTimeOffset? SentAt { get; private set; }

    public DateTimeOffset? CompletedAt { get; private set; }

    /// <summary>
    /// Counts a document issued into the batch. The first one fixes the environment of the batch.
    /// </summary>
    /// <exception cref="InvalidOperationException">If the batch is not open, is full or has another environment.</exception>
    public void Add(int typeEnvironmentId)
    {
        EnsureIn(DocumentBatchStatus.Open);
        if (DocumentCount >= MaxDocuments || (TypeEnvironmentId is { } current && current != typeEnvironmentId))
        {
            throw new InvalidOperationException($"Batch {Id} cannot take another document of environment {typeEnvironmentId}.");
        }

        TypeEnvironmentId = typeEnvironmentId;
        DocumentCount++;
    }

    /// <summary>The batch is closed and waits for the Worker to send it.</summary>
    public void Queue(DateTimeOffset now)
    {
        EnsureIn(DocumentBatchStatus.Open);
        if (DocumentCount == 0)
        {
            throw new InvalidOperationException($"Batch {Id} has no documents.");
        }

        _status = DocumentBatchStatus.Queued;
        QueuedAt = now;
    }

    /// <summary>SendBillAsync took the ZIP: from now on GetStatusZip with <see cref="ZipKey"/> tells each document's verdict.</summary>
    public void MarkSent(string zipKey, DateTimeOffset sentAt)
    {
        EnsureIn(DocumentBatchStatus.Queued);
        ZipKey = zipKey;
        SentAt = sentAt;
        _status = DocumentBatchStatus.Sent;
    }

    /// <summary>
    /// The batch has nothing more to follow: every document has its verdict, or is followed on its own (with GetStatus and
    /// its code) because the DIAN may have received the ZIP without answering its ZipKey.
    /// </summary>
    public void Complete(DateTimeOffset now, DateTimeOffset? sentAt = null)
    {
        if (_status is not (DocumentBatchStatus.Queued or DocumentBatchStatus.Sent))
        {
            throw new InvalidOperationException($"Batch {Id} cannot complete from {_status}.");
        }

        SentAt ??= sentAt;
        CompletedAt = now;
        _status = DocumentBatchStatus.Completed;
    }

    /// <summary>The ZIP never reached the DIAN (or the DIAN refused the message): its documents failed with it.</summary>
    public void Fail(DateTimeOffset now)
    {
        EnsureIn(DocumentBatchStatus.Queued);
        CompletedAt = now;
        _status = DocumentBatchStatus.Failed;
    }

    private void EnsureIn(DocumentBatchStatus expected)
    {
        if (_status != expected)
        {
            throw new InvalidOperationException($"Batch {Id} is {_status}, not {expected}.");
        }
    }
}

/// <summary>A document of a batch and the name of its XML inside the ZIP (for example <c>fv09018462800002500000166.xml</c>).</summary>
public sealed class DocumentBatchEntry
{
    public Guid DocumentId { get; init; }

    public required string FileName { get; init; }
}

/// <summary>State of a batch (<c>document_batches.status</c>, smallint).</summary>
public enum DocumentBatchStatus : short
{
    /// <summary>Takes documents.</summary>
    Open = 1,

    /// <summary>Closed; the Worker sends it with SendBillAsync.</summary>
    Queued = 2,

    /// <summary>The DIAN took the ZIP and gave its ZipKey; the Worker asks GetStatusZip.</summary>
    Sent = 3,

    /// <summary>Nothing more to follow: see each document.</summary>
    Completed = 4,

    /// <summary>The ZIP never reached the DIAN; its documents failed.</summary>
    Failed = 5,
}
